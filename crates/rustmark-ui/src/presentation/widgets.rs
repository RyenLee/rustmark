//! `presentation::widgets` —— egui 布局不变式的封装层（T8）。
//!
//! # 这个模块收什么
//!
//! 只收**满足全部三条**的东西：
//!
//! 1. **同一配方在 ≥2 处出现**——只出现一次的不叫模式，叫写法；
//! 2. **写错不报错**——错误只表现为视觉错位或交互失效，编译期、类型系统、
//!    常规单测都拦不住；
//! 3. **正确写法与直觉写法不同**——直觉写法看起来完全合理（这正是它反复
//!    被写错的原因），所以只靠注释提醒不够。
//!
//! 每条封装都对应至少一个已归档缺陷，文档里写明编号与根因。这不是文档洁癖：
//! 下一个改动的人需要知道「为什么不能图省事直接调 egui」。
//!
//! # 这个模块**不收**什么（同样是决策）
//!
//! | 不收的东西 | 理由 |
//! |---|---|
//! | `vec2` / `pos2` / `Rect::from_min_size` / `Sense::hover` / `Color32` / `FontId` / `Stroke` 等构造器 | 它们是 egui 的**稳定词汇**。包一层 `widgets::v2(x, y)` 只是多一次跳转；升级时反而要同时改封装与调用点两处，比直接改一处更贵。 |
//! | `ui.horizontal_top` / `Separator::default().spacing(1.0)` / 按 `clip_rect` 推绝对坐标 / `add_space` 双计间距 / `max_rect` 污染后的块级限宽 | 它们是**调用点的选择**，不是一段可复用的代码。封成别名会隐藏 egui API 本身——而相关注释引用的正是 egui 的名字（`Placer::expand_to_include_rect`、`UiBuilder::sense`），隐藏后注释与代码对不上，反而更难查。这五条以「纪律条目」形式记在 [`rustmark_core::presentation`] 的模块文档与 `docs/06-表现层与交互实现.md` 里。 |
//! | 按钮 / 标签 / 开关这类普通控件 | egui 自带即可。二次封装普通控件是「自建 GUI 框架」的起点：调用点失去 egui 文档与示例的直接对应关系，收益为零。 |
//!
//! # 与「收敛 egui 升级面」的关系
//!
//! T8 的预期收益写的是「下一次 egui 大版本升级受影响面从几十处散点收敛到
//! 几个封装点」。**这个收益只对不变式成立，对普通 API 不成立**：
//! egui 0.33→0.37 真正改签名的是 `Rounding`→`CornerRadius`、`Margin` 由
//! `f32` 改 `i8`、`Frame::none()`→`Frame::new()` 这类**构造器**，它们恰好
//! 是上表「不收」的一类，且都是机械替换（编译器逐个报错，改起来是体力活
//! 而非判断活）。真正的成本在**语义变化**上——`Ui::horizontal` 的初始高、
//! `scope_builder().response` 的返回语义、面板按内容 rect 保留宽度——那些
//! 没有一处是「封装一次就能免疫」的，只能靠真帧探针测试钉住。
//!
//! 所以本模块的目标不是「薄薄包一层 egui」，而是「让已经踩过的坑在结构上
//! 不可能再踩」。参见 `docs/adr/ADR-008-widgets-layer-boundary.md`。

