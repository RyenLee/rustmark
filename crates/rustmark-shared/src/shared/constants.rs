//! 跨层共用的阈值常量（单一真源）。
//!
//! 这些值此前在 core / ui / root 各自复制一份（500KB 大文件阈值、150ms 防抖、
//! 0.5pt 滚动容差），改一处漏两处就会行为分叉。放在 shared 的理由：
//!
//! - core 内部多个层都要用；
//! - `rustmark-ui` 与 root 都依赖 core，可直接引用，不新增任何依赖边；
//! - 数值语义与层无关，属于典型的共享内核内容。
//!
//! **本模块只放"同一语义、多处消费"的常量**；只在单个文件内使用的阈值
//! 仍留在原地，避免把 shared 变成无差别常量垃圾桶。

/// 大文件降级阈值（字节，500 KiB）。
///
/// FR-06：源文档超过该值时预览只做截断/纯文本降级、增量高亮不再启用。
/// 三处消费者（应用层截断、基础设施增量高亮、表现层排版）必须同值。
pub const LARGE_FILE_BYTES: usize = 500 * 1024;

/// 交互防抖窗口（毫秒，FR-01）。
///
/// 预览渲染、状态栏统计、高亮静止判定共用：打字期不重算，停手满该窗口后刷新。
pub const DEBOUNCE_MS: u64 = 150;

/// 滚动偏移变化的最小感知量（点）。
///
/// 小于该值的偏移变化视为像素取整抖动，不触发同步/跳转。
pub const SCROLL_MOVE_EPS: f32 = 0.5;
